#!/usr/bin/env python3
"""Atomically render the environment selected by a composed envy manifest."""

from __future__ import annotations

import json
import os
import re
import shlex
import sys
import tempfile
from pathlib import Path
from typing import Any


KEY = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def assignment(key: str, value: str) -> str:
    if not KEY.fullmatch(key):
        raise ValueError(f"invalid environment key: {key}")
    return f"export {key}={shlex.quote(value)}"


def render(manifest: dict[str, Any], state: dict[str, Any], root: str) -> str:
    workspace = str(manifest.get("workspace_root", root))
    lines = [
        "# Generated by envy; do not edit.",
        assignment("ENVY_ROOT", root),
        assignment("WORKSPACE_ROOT", workspace),
        assignment("ENVY_PLATFORM", str(state.get("platform", "unknown"))),
        assignment(
            "ENVY_PLATFORM_HIERARCHY",
            str(state.get("platform_hierarchy", state.get("platform", "unknown"))),
        ),
        assignment("ENVY_SHELL", str(state.get("shell", "unknown"))),
    ]
    for key, value in manifest.get("environment", {}).items():
        if key in {
            "ENVY_ROOT",
            "WORKSPACE_ROOT",
            "ENVY_PLATFORM",
            "ENVY_PLATFORM_HIERARCHY",
            "ENVY_SHELL",
        }:
            raise ValueError(f"bundle cannot replace reserved environment key: {key}")
        lines.append(assignment(key, str(value)))

    state_features = state.get("features", {})
    for name, definition in manifest.get("features", {}).items():
        feature = state_features.get(name, {})
        if not feature.get("enabled") or feature.get("status") != "current":
            continue
        environment = definition.get("env")
        if not isinstance(environment, dict) or not environment:
            continue
        lines.extend(("", f"# {name}"))
        for key, raw_value in environment.items():
            values = raw_value if isinstance(raw_value, list) else [raw_value]
            if key == "PATH+":
                for value in values:
                    lines.append(f'export PATH="$PATH":{shlex.quote(str(value))}')
            elif len(values) == 1:
                lines.append(assignment(key, str(values[0])))
            else:
                raise ValueError(
                    f"non-PATH environment value must be scalar: {name}.{key}"
                )

    adb = state_features.get("adb", {})
    data = adb.get("data", {}) if isinstance(adb.get("data"), dict) else {}
    sdk = data.get("sdk_root")
    if adb.get("enabled") and adb.get("status") == "current" and sdk:
        lines.extend(
            (
                "",
                "# adb",
                assignment("ANDROID_SDK_ROOT", str(sdk)),
                'export ANDROID_HOME="$ANDROID_SDK_ROOT"',
                'export PATH="$ANDROID_SDK_ROOT/platform-tools:$PATH"',
            )
        )
    secrets = state_features.get("secrets", {})
    secret_settings = manifest.get("settings", {}).get("secrets", {})
    secret_target = (
        secret_settings.get("target") if isinstance(secret_settings, dict) else None
    )
    if (
        secrets.get("enabled")
        and secrets.get("status") == "current"
        and isinstance(secret_target, str)
    ):
        lines.extend(
            (
                "",
                "# secrets",
                assignment("ENVY_SECRETS_FILE", str(Path(secret_target).expanduser())),
            )
        )
    lines.extend(("", ""))
    return "\n".join(lines)


def main() -> int:
    if len(sys.argv) != 5:
        return 2
    manifest_path = Path(sys.argv[1])
    state_path = Path(sys.argv[2])
    output_path = Path(sys.argv[3])
    root = sys.argv[4]
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    state = json.loads(state_path.read_text(encoding="utf-8"))
    output_path.parent.mkdir(parents=True, exist_ok=True)
    content = render(manifest, state, root)
    fd, temp_name = tempfile.mkstemp(prefix="init-sh.", dir=output_path.parent)
    try:
        os.fchmod(fd, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(content)
        os.replace(temp_name, output_path)
    finally:
        if os.path.exists(temp_name):
            os.unlink(temp_name)
    print(f"Generated {output_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
